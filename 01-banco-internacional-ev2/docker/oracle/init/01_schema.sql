-- ------------------------------------------------------------
-- clientes
-- ------------------------------------------------------------
CREATE TABLE clientes (
    id               NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre           VARCHAR2(60)  NOT NULL,
    apellido         VARCHAR2(60)  NOT NULL,
    dni              VARCHAR2(15)  NOT NULL UNIQUE,
    email            VARCHAR2(120) NOT NULL UNIQUE,
    fecha_nacimiento DATE          NOT NULL
);

-- ------------------------------------------------------------
-- cuentas (1:1 con clientes)
-- ------------------------------------------------------------
CREATE TABLE cuentas (
    id              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente      NUMBER        NOT NULL UNIQUE,
    numero_cuenta   VARCHAR2(20)  NOT NULL UNIQUE,
    tipo            VARCHAR2(20)  DEFAULT 'corriente' NOT NULL,
    saldo           NUMBER(14,2)  DEFAULT 0 NOT NULL,
    fecha_apertura  DATE          DEFAULT SYSDATE NOT NULL,
    CONSTRAINT fk_cuenta_cliente FOREIGN KEY (id_cliente) REFERENCES clientes(id)
);

-- ------------------------------------------------------------
-- movimientos
-- ------------------------------------------------------------
CREATE TABLE movimientos (
    id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cuenta   NUMBER        NOT NULL,
    tipo        VARCHAR2(10)  NOT NULL,
    monto       NUMBER(14,2)  NOT NULL,
    descripcion VARCHAR2(200),
    fecha       DATE          DEFAULT SYSDATE NOT NULL,
    CONSTRAINT fk_mov_cuenta FOREIGN KEY (id_cuenta) REFERENCES cuentas(id),
    CONSTRAINT ck_mov_tipo   CHECK (tipo IN ('deposito', 'retiro'))
);

-- ------------------------------------------------------------
-- prestamos
-- ------------------------------------------------------------
CREATE TABLE prestamos (
    id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente  NUMBER        NOT NULL,
    monto       NUMBER(14,2)  NOT NULL,
    tasa        NUMBER(5,2)   NOT NULL,
    plazo_meses NUMBER(3)     NOT NULL,
    estado      VARCHAR2(20)  DEFAULT 'activo' NOT NULL,
    condiciones VARCHAR2(300),
    fecha       DATE          DEFAULT SYSDATE NOT NULL,
    CONSTRAINT fk_prestamo_cliente FOREIGN KEY (id_cliente) REFERENCES clientes(id),
    CONSTRAINT ck_prestamo_estado  CHECK (estado IN ('activo', 'mora', 'pagado'))
);

-- ------------------------------------------------------------
-- usuarios (autenticacion; id_cliente nulo para el ejecutivo)
-- Password en texto plano a proposito: vulnerabilidad documentada.
-- ------------------------------------------------------------
CREATE TABLE usuarios (
    id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente NUMBER,
    username   VARCHAR2(40) NOT NULL UNIQUE,
    password   VARCHAR2(60) NOT NULL,
    rol        VARCHAR2(15) NOT NULL,
    CONSTRAINT fk_user_cliente FOREIGN KEY (id_cliente) REFERENCES clientes(id),
    CONSTRAINT ck_user_rol     CHECK (rol IN ('cliente', 'ejecutivo'))
);

